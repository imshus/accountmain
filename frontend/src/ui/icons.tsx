export type IconName = keyof typeof PATHS;
export const ICON_NAMES = Object.keys(PATHS) as IconName[];

type Props = {
  name: IconName;
  /** Pixel size; default 20 (the design's .ico). */
  size?: number;
  /** Stroke width; default 2. */
  stroke?: number;
  className?: string;
  /** Give a label only when the icon stands alone and means something; otherwise it is hidden from screen readers. */
  label?: string;
};

/** One of the design's line icons. Colour comes from `color` (currentColor). */
export function Icon({ name, size = 20, stroke, className, label }: Props) {
  return (
    <svg
      className={`ui-ico${className ? ` ${className}` : ""}`}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      style={stroke ? { strokeWidth: stroke } : undefined}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}
